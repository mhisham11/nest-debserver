import asyncio
import base64
from dataclasses import dataclass
import logging
from typing import Any
import httpx
from bot.config import ConfigManager

logger = logging.getLogger("bot.llm")


@dataclass
class LLMResponse:
    text: str
    model: str
    tokens_used: int


@dataclass
class ImageGenResponse:
    image_bytes: bytes
    model: str
    tokens_used: int


class HackClubLLMClient:
    def __init__(
        self,
        api_key: str,
        config_mgr: ConfigManager,
        http_client: httpx.AsyncClient,
    ) -> None:
        self.api_key = api_key
        self.config_mgr = config_mgr
        self.http = http_client
        self._sem_limit = config_mgr.get().limits.max_concurrent_requests
        self._semaphore = asyncio.Semaphore(self._sem_limit)

    def _get_semaphore(self) -> asyncio.Semaphore:
        current_limit = self.config_mgr.get().limits.max_concurrent_requests
        if current_limit != self._sem_limit:
            self._sem_limit = current_limit
            self._semaphore = asyncio.Semaphore(current_limit)
        return self._semaphore

    async def chat_completion(
        self,
        messages: list[dict[str, Any]],
        models: list[str],
        guild_id: int,
    ) -> LLMResponse | None:
        cfg = self.config_mgr.get()
        url = f"{cfg.hackclub.base_url.rstrip('/')}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        async with self._get_semaphore():
            for model in models:
                payload = {
                    "model": model,
                    "messages": messages,
                    "max_tokens": cfg.limits.max_output_tokens,
                }
                try:
                    resp = await self.http.post(
                        url,
                        headers=headers,
                        json=payload,
                        timeout=cfg.hackclub.request_timeout_seconds,
                    )
                    if resp.status_code >= 400:
                        logger.warning(
                            "Chat model %s failed in guild %d with HTTP %d",
                            model,
                            guild_id,
                            resp.status_code,
                        )
                        continue

                    data = resp.json()
                    choices = data.get("choices") or []
                    if not choices:
                        logger.warning("Chat model %s returned empty choices in guild %d", model, guild_id)
                        continue

                    content = (choices[0].get("message") or {}).get("content")
                    if isinstance(content, list):
                        content = "".join(
                            part.get("text", "") for part in content if isinstance(part, dict)
                        )
                    text = str(content or "").strip()
                    if not text:
                        logger.warning("Chat model %s returned empty text in guild %d", model, guild_id)
                        continue

                    usage = data.get("usage") or {}
                    tokens = int(
                        usage.get("total_tokens")
                        or (int(usage.get("prompt_tokens", 0)) + int(usage.get("completion_tokens", 0)))
                    )
                    logger.info(
                        "Guild %d reply generated by model=%s tokens=%d",
                        guild_id,
                        model,
                        tokens,
                    )
                    return LLMResponse(text=text, model=model, tokens_used=tokens)

                except Exception as exc:
                    logger.warning(
                        "Exception calling chat model %s in guild %d: %s",
                        model,
                        guild_id,
                        type(exc).__name__,
                    )
                    continue

        logger.error("All candidate chat models failed for guild %d", guild_id)
        return None

    async def generate_image(
        self,
        prompt: str,
        models: list[str],
        guild_id: int,
    ) -> ImageGenResponse | None:
        cfg = self.config_mgr.get()
        endpoint = cfg.hackclub.image_endpoint
        if not endpoint.startswith("/"):
            endpoint = "/" + endpoint
        url = f"{cfg.hackclub.base_url.rstrip('/')}{endpoint}"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }

        async with self._get_semaphore():
            for model in models:
                payload = {
                    "model": model,
                    "prompt": prompt,
                    "n": 1,
                    "response_format": "b64_json",
                }
                try:
                    resp = await self.http.post(
                        url,
                        headers=headers,
                        json=payload,
                        timeout=cfg.hackclub.request_timeout_seconds,
                    )
                    if resp.status_code >= 400:
                        logger.warning(
                            "Image model %s failed in guild %d with HTTP %d",
                            model,
                            guild_id,
                            resp.status_code,
                        )
                        continue

                    data = resp.json()
                    items = data.get("data") or []
                    if not items:
                        logger.warning("Image model %s returned no data items in guild %d", model, guild_id)
                        continue

                    first = items[0]
                    img_bytes: bytes | None = None
                    if "b64_json" in first and first["b64_json"]:
                        img_bytes = base64.b64decode(first["b64_json"])
                    elif "url" in first and first["url"]:
                        img_resp = await self.http.get(
                            first["url"],
                            timeout=cfg.hackclub.request_timeout_seconds,
                        )
                        img_resp.raise_for_status()
                        img_bytes = img_resp.content

                    if not img_bytes:
                        logger.warning("Image model %s produced empty image bytes in guild %d", model, guild_id)
                        continue

                    usage = data.get("usage") or {}
                    tokens = int(usage.get("total_tokens") or 0)
                    if tokens <= 0:
                        tokens = cfg.budget.image_token_cost

                    logger.info(
                        "Guild %d image generated by model=%s tokens=%d",
                        guild_id,
                        model,
                        tokens,
                    )
                    return ImageGenResponse(image_bytes=img_bytes, model=model, tokens_used=tokens)

                except Exception as exc:
                    logger.warning(
                        "Exception calling image model %s in guild %d: %s",
                        model,
                        guild_id,
                        type(exc).__name__,
                    )
                    continue

        logger.error("All candidate image models failed for guild %d", guild_id)
        return None
